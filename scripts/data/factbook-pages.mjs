// Which pages of The World Factbook say what of which country of the game: scripts/data/fetch.mjs brings
// them and scripts/data/figures.mjs reads them.
//
// The book files each country under a code of its own, which is not the one the game knows it by (`sp` is
// Spain, `gm` Germany, `sx` South Georgia), so the page of a country is told by what the page itself says:
// the internet code it gives first (".es"), or, where it gives none, its name. A country the book has in two
// pages has both (Palestine: the Gaza Strip and the West Bank). Seven countries of the game have no page:
// the book does not tell Åland, the Caribbean Netherlands and the five overseas departments of France
// apart from Finland, the Netherlands and France.
//
// Each page comes with the name git gives the file (`git hash-object`) at the commit `fetch.mjs` pins, which
// is how a download is known to be the page that was read here. With another edition of the book the whole
// list is made again: every page of a country in that commit, its name for git, and the country whose
